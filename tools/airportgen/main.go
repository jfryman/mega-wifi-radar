// Command airportgen writes src/airports.c: the home-airport table for the
// config screen, from OurAirports (public domain): large airports with
// scheduled service, sorted by ICAO ident.
//
//	cd tools && go run ./airportgen -o ../src/airports.c
package main

import (
	"encoding/csv"
	"flag"
	"fmt"
	"io"
	"log"
	"math"
	"net/http"
	"os"
	"sort"
	"strconv"
	"strings"
)

const src = "https://davidmegginson.github.io/ourairports-data/airports.csv"
const nameLen = 24

type airport struct {
	icao     string
	name     string
	lat, lon int32 // 1e-4 deg
}

func main() {
	out := flag.String("o", "src/airports.c", "output C file")
	in := flag.String("csv", "", "local airports.csv (default: download)")
	flag.Parse()

	var r io.Reader
	if *in != "" {
		f, err := os.Open(*in)
		if err != nil {
			log.Fatal(err)
		}
		defer f.Close()
		r = f
	} else {
		resp, err := http.Get(src)
		if err != nil {
			log.Fatal(err)
		}
		defer resp.Body.Close()
		r = resp.Body
	}
	rows, err := csv.NewReader(r).ReadAll()
	if err != nil {
		log.Fatal(err)
	}
	col := map[string]int{}
	for i, h := range rows[0] {
		col[h] = i
	}
	var aps []airport
	for _, row := range rows[1:] {
		id := row[col["ident"]]
		if row[col["type"]] != "large_airport" || row[col["scheduled_service"]] != "yes" || len(id) != 4 {
			continue
		}
		lat, _ := strconv.ParseFloat(row[col["latitude_deg"]], 64)
		lon, _ := strconv.ParseFloat(row[col["longitude_deg"]], 64)
		aps = append(aps, airport{
			icao: strings.ToUpper(id),
			name: ascii(row[col["name"]]),
			lat:  int32(math.Round(lat * 1e4)),
			lon:  int32(math.Round(lon * 1e4)),
		})
	}
	sort.Slice(aps, func(i, j int) bool { return aps[i].icao < aps[j].icao })

	var b strings.Builder
	fmt.Fprintf(&b, "/* Generated by tools/airportgen from OurAirports (public domain). Do not edit. */\n")
	fmt.Fprintf(&b, "#include \"airports.h\"\n\n")
	fmt.Fprintf(&b, "const struct airport airports[AIRPORT_COUNT] = {\n")
	for _, a := range aps {
		fmt.Fprintf(&b, "    { \"%s\", %d, %d, \"%s\" },\n", a.icao, a.lat, a.lon, a.name)
	}
	fmt.Fprintf(&b, "};\n")
	if err := os.WriteFile(*out, []byte(b.String()), 0o644); err != nil {
		log.Fatal(err)
	}
	h := strings.TrimSuffix(*out, ".c") + "_count.h"
	cnt := fmt.Sprintf("/* Generated by tools/airportgen. */\n#define AIRPORT_COUNT %d\n#define AIRPORT_NAME_LEN %d\n", len(aps), nameLen)
	if err := os.WriteFile(h, []byte(cnt), 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("airportgen: %d airports -> %s\n", len(aps), *out)
}

// ascii keeps printable ASCII (the font has no accents), uppercases, and trims to nameLen.
func ascii(s string) string {
	var b strings.Builder
	for _, r := range strings.ToUpper(s) {
		switch {
		case r == '"' || r == '\\':
			continue
		case r >= 0x20 && r < 0x7F:
			b.WriteRune(r)
		case r > 0x7F:
			b.WriteRune(fold(r))
		}
		if b.Len() >= nameLen {
			break
		}
	}
	return strings.TrimSpace(b.String())
}

func fold(r rune) rune {
	switch {
	case strings.ContainsRune("ÀÁÂÃÄÅĀĂĄ", r):
		return 'A'
	case strings.ContainsRune("ÇĆČ", r):
		return 'C'
	case strings.ContainsRune("ÈÉÊËĒĖĘĚ", r):
		return 'E'
	case strings.ContainsRune("ÌÍÎÏĪĮİ", r):
		return 'I'
	case strings.ContainsRune("ÑŃŇ", r):
		return 'N'
	case strings.ContainsRune("ÒÓÔÕÖØŌŐ", r):
		return 'O'
	case strings.ContainsRune("ÙÚÛÜŪŮŰ", r):
		return 'U'
	case strings.ContainsRune("ÝŸ", r):
		return 'Y'
	case strings.ContainsRune("ŚŠŞ", r):
		return 'S'
	case strings.ContainsRune("ŹŻŽ", r):
		return 'Z'
	}
	return '?'
}
