// Command tzgen writes relay/airport_tz.csv: the IANA time zone of each of the cart's home airports (large
// airports with scheduled service, as tools/airportgen picks them), so the relay's logbook days end at the airport's
// midnight (lode/relay/logbook.md). OurAirports has no time zones, so each airport takes the zone of the nearest
// GeoNames city of 15,000+ people (CC BY 4.0, credited in the manual and docs/relay.md).
//
//	cd tools && go run ./tzgen -o ../relay/airport_tz.csv
package main

import (
	"archive/zip"
	"bytes"
	"encoding/csv"
	"flag"
	"fmt"
	"io"
	"log"
	"math"
	"net/http"
	"os"
	"sort"
	"strconv"
	"strings"
)

const (
	airportsURL = "https://davidmegginson.github.io/ourairports-data/airports.csv"
	citiesURL   = "https://download.geonames.org/export/dump/cities15000.zip"
)

func fetch(local, url string) []byte {
	if local != "" {
		b, err := os.ReadFile(local)
		if err != nil {
			log.Fatal(err)
		}
		return b
	}
	resp, err := http.Get(url)
	if err != nil {
		log.Fatal(err)
	}
	defer resp.Body.Close()
	b, err := io.ReadAll(resp.Body)
	if err != nil {
		log.Fatal(err)
	}
	return b
}

type city struct {
	lat, lon float64
	tz       string
}

func main() {
	out := flag.String("o", "relay/airport_tz.csv", "output CSV")
	apIn := flag.String("airports", "", "local airports.csv (default: download)")
	ctIn := flag.String("cities", "", "local cities15000.zip (default: download)")
	flag.Parse()

	zb := fetch(*ctIn, citiesURL)
	zr, err := zip.NewReader(bytes.NewReader(zb), int64(len(zb)))
	if err != nil {
		log.Fatal(err)
	}
	var cities []city
	for _, f := range zr.File {
		if f.Name != "cities15000.txt" {
			continue
		}
		rc, _ := f.Open()
		data, _ := io.ReadAll(rc)
		rc.Close()
		for _, line := range strings.Split(string(data), "\n") {
			c := strings.Split(line, "\t")
			if len(c) < 18 || c[17] == "" {
				continue
			}
			lat, e1 := strconv.ParseFloat(c[4], 64)
			lon, e2 := strconv.ParseFloat(c[5], 64)
			if e1 == nil && e2 == nil {
				cities = append(cities, city{lat, lon, c[17]})
			}
		}
	}
	if len(cities) == 0 {
		log.Fatal("no cities read")
	}

	rows, err := csv.NewReader(bytes.NewReader(fetch(*apIn, airportsURL))).ReadAll()
	if err != nil {
		log.Fatal(err)
	}
	col := map[string]int{}
	for i, h := range rows[0] {
		col[h] = i
	}
	var lines []string
	for _, row := range rows[1:] {
		id := row[col["ident"]]
		if row[col["type"]] != "large_airport" || row[col["scheduled_service"]] != "yes" || len(id) != 4 {
			continue
		}
		lat, _ := strconv.ParseFloat(row[col["latitude_deg"]], 64)
		lon, _ := strconv.ParseFloat(row[col["longitude_deg"]], 64)
		best, bd := "", math.Inf(1)
		for _, c := range cities {
			dl := (c.lon - lon) * math.Cos(lat*math.Pi/180)
			if d := (c.lat-lat)*(c.lat-lat) + dl*dl; d < bd {
				best, bd = c.tz, d
			}
		}
		lines = append(lines, fmt.Sprintf("%s,%.4f,%.4f,%s", strings.ToUpper(id), lat, lon, best))
	}
	sort.Strings(lines)
	body := "# airport,lat,lon,iana_tz: generated by tools/tzgen (OurAirports, public domain; zones from the nearest GeoNames city, CC BY 4.0)\n" +
		strings.Join(lines, "\n") + "\n"
	if err := os.WriteFile(*out, []byte(body), 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("%s: %d airports, %d cities", *out, len(lines), len(cities))
}
