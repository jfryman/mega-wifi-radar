// Command runwaygen writes relay/runways.csv: the runways of the cart's home airports (large airports with
// scheduled service, as tools/airportgen picks them), for the relay's video maps (lode/plans/video-maps.md).
// From OurAirports (public domain). Closed runways and runways without both ends' positions are left out.
//
//	cd tools && go run ./runwaygen -o ../relay/runways.csv
package main

import (
	"encoding/csv"
	"flag"
	"fmt"
	"io"
	"log"
	"net/http"
	"os"
	"sort"
	"strconv"
	"strings"
)

const base = "https://davidmegginson.github.io/ourairports-data/"

func load(local, name string) [][]string {
	var r io.Reader
	if local != "" {
		f, err := os.Open(local)
		if err != nil {
			log.Fatal(err)
		}
		defer f.Close()
		r = f
	} else {
		resp, err := http.Get(base + name)
		if err != nil {
			log.Fatal(err)
		}
		defer resp.Body.Close()
		r = resp.Body
	}
	rows, err := csv.NewReader(r).ReadAll()
	if err != nil {
		log.Fatal(err)
	}
	return rows
}

func cols(h []string) map[string]int {
	m := map[string]int{}
	for i, c := range h {
		m[c] = i
	}
	return m
}

func main() {
	out := flag.String("o", "relay/runways.csv", "output CSV")
	apIn := flag.String("airports", "", "local airports.csv (default: download)")
	rwIn := flag.String("runways", "", "local runways.csv (default: download)")
	flag.Parse()

	aps := load(*apIn, "airports.csv")
	ac := cols(aps[0])
	keep := map[string]bool{}
	for _, row := range aps[1:] {
		id := row[ac["ident"]]
		if row[ac["type"]] == "large_airport" && row[ac["scheduled_service"]] == "yes" && len(id) == 4 {
			keep[strings.ToUpper(id)] = true
		}
	}
	rws := load(*rwIn, "runways.csv")
	rc := cols(rws[0])
	var lines []string
	for _, row := range rws[1:] {
		id := strings.ToUpper(row[rc["airport_ident"]])
		if !keep[id] || row[rc["closed"]] == "1" {
			continue
		}
		var f [4]float64
		ok := true
		for i, c := range []string{"le_latitude_deg", "le_longitude_deg", "he_latitude_deg", "he_longitude_deg"} {
			v, err := strconv.ParseFloat(row[rc[c]], 64)
			if err != nil {
				ok = false
			}
			f[i] = v
		}
		if !ok {
			continue
		}
		lines = append(lines, fmt.Sprintf("%s,%s,%.5f,%.5f,%s,%.5f,%.5f", id, row[rc["le_ident"]], f[0], f[1],
			row[rc["he_ident"]], f[2], f[3]))
	}
	sort.Strings(lines)
	body := "# airport,le_ident,le_lat,le_lon,he_ident,he_lat,he_lon: generated by tools/runwaygen from OurAirports (public domain)\n" +
		strings.Join(lines, "\n") + "\n"
	if err := os.WriteFile(*out, []byte(body), 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("%s: %d runways at %d airports", *out, len(lines), len(keep))
}
