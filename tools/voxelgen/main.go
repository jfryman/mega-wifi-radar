// voxelgen writes the cockpit speed spike's terrain (spike/voxel/src/terrain.c): a procedural,
// toroidal 128x128 heightmap (64 levels) with a river and a runway, its colour map (slope-shaded,
// each byte two identical 4-bit pixels), the palette and a Q14 sine table.
//
//	cd tools && go run ./voxelgen -o ../spike/voxel/src
package main

import (
	"flag"
	"fmt"
	"math"
	"math/rand"
	"os"
	"path/filepath"
	"strings"
)

const n = 128

// Palette indices (PAL0). 0 is transparent; 1-3 sky, deep to pale.
const (
	cWaterDark = 4 + iota
	cWaterLight
	cGrassDark
	cGrass
	cGrassLight
	cForestDark
	cForest
	cForestLight
	cRockDark
	cRock
	cRunway
	cWhite
)

// Genesis colours, 0xBGR with 3 bits per channel (even nibbles).
var palette = [16]uint16{
	0x000, 0xA42, 0xC86, 0xECA, // -, sky deep, mid, pale
	0x620, 0xA60, // water
	0x042, 0x064, 0x286, // grass
	0x022, 0x042, 0x264, // forest
	0x246, 0x468, // rock
	0x666, 0xEEE, // runway, white
}

func main() {
	out := flag.String("o", "../spike/voxel/src", "output directory")
	flag.Parse()

	h := diamondSquare(rand.New(rand.NewSource(1989)))
	var hm, cm [n * n]byte

	// river: a sinuous band through the map, carved to water level
	for y := 0; y < n; y++ {
		cx := 64 + 22*math.Sin(float64(y)*2*math.Pi/n) + 6*math.Sin(float64(y)*6*math.Pi/n)
		for x := 0; x < n; x++ {
			d := math.Abs(wrapd(float64(x) - cx))
			if d < 3 {
				h[y*n+x] = 0
			} else if d < 7 {
				h[y*n+x] *= (d - 3) / 4
			}
		}
	}
	// runway: flatten a 3x26 strip, track 020/200-ish (straight up the map here)
	const rx, ry0, ry1 = 24, 40, 66
	for y := ry0 - 4; y < ry1+4; y++ {
		for x := rx - 4; x <= rx+4; x++ {
			h[y*n+x] = 0.18
		}
	}

	hmax := 0
	for i := range h {
		hm[i] = byte(math.Round(clamp(h[i], 0, 1) * 63))
		hmax = max(hmax, int(hm[i]))
	}
	for y := 0; y < n; y++ {
		for x := 0; x < n; x++ {
			i := y*n + x
			// light from the north-west: brighter on slopes facing it
			s := int(hm[i]) - int(hm[wrap(y-1)*n+wrap(x-1)])
			shade := 1
			if s > 1 {
				shade = 2
			} else if s < -1 {
				shade = 0
			}
			var c int
			switch v := hm[i]; {
			case v == 0:
				c = cWaterDark + (x+y)%2
			case v < 22:
				c = cGrassDark + shade
			case v < 44:
				c = cForestDark + shade
			case v < 58:
				c = cRockDark + min(shade, 1)
			default:
				c = cWhite
			}
			if x >= rx-1 && x <= rx+1 && y >= ry0 && y < ry1 {
				c = cRunway
				if x == rx && y%3 != 0 {
					c = cWhite
				}
			}
			cm[i] = byte(c<<4 | c)
		}
	}

	var b strings.Builder
	b.WriteString("/* Generated by tools/voxelgen. Do not edit. */\n#include \"terrain.h\"\n\n")
	b.WriteString("const u16 terrain_pal[16] = {")
	for i, c := range palette {
		if i%8 == 0 {
			b.WriteString("\n    ")
		}
		fmt.Fprintf(&b, "0x%03X, ", c)
	}
	b.WriteString("\n};\n\n")
	writeBytes(&b, "terrain_h", hm[:])
	writeBytes(&b, "terrain_c", cm[:])
	// for the assembly inner loop: the byte offset into a 32-entry s16 row table (height / 2, times 2)
	var h2 [n * n]byte
	for i, v := range hm {
		h2[i] = v >> 1 * 2
	}
	writeBytes(&b, "terrain_h2", h2[:])
	b.WriteString("const s16 sin_q14[256] = {")
	for i := 0; i < 256; i++ {
		if i%12 == 0 {
			b.WriteString("\n    ")
		}
		fmt.Fprintf(&b, "%d, ", int(math.Round(16384*math.Sin(float64(i)*2*math.Pi/256))))
	}
	b.WriteString("\n};\n")
	must(os.WriteFile(filepath.Join(*out, "terrain.c"), []byte(b.String()), 0o644))

	hdr := `/* Generated by tools/voxelgen. Do not edit. */
#pragma once
#include <genesis.h>

#define TERRAIN_N 128                       /* cells per side, wraps */
extern const u16 terrain_pal[16];
extern const u8 terrain_h[TERRAIN_N * TERRAIN_N];   /* 0..63 */
extern const u8 terrain_c[TERRAIN_N * TERRAIN_N];   /* colour byte: two identical pixels */
extern const u8 terrain_h2[TERRAIN_N * TERRAIN_N];  /* (height / 2) * 2: byte offset into a 32-entry s16 table */
extern const s16 sin_q14[256];                      /* 256 steps per turn */
#define TERRAIN_HMAX %d                     /* highest level in the map */
#define SKY_DEEP 0x11
#define SKY_MID  0x22
#define SKY_PALE 0x33
`
	must(os.WriteFile(filepath.Join(*out, "terrain.h"), []byte(fmt.Sprintf(hdr, hmax)), 0o644))
}

// diamondSquare returns n*n heights in [0,1], tiling seamlessly.
func diamondSquare(r *rand.Rand) []float64 {
	h := make([]float64, n*n)
	at := func(x, y int) *float64 { return &h[wrap(y)*n+wrap(x)] }
	amp := 1.0
	for step := n; step > 1; step /= 2 {
		half := step / 2
		for y := 0; y < n; y += step {
			for x := 0; x < n; x += step {
				avg := (*at(x, y) + *at(x+step, y) + *at(x, y+step) + *at(x+step, y+step)) / 4
				*at(x+half, y+half) = avg + (r.Float64()-0.5)*amp
			}
		}
		for y := 0; y < n; y += half {
			for x := (y/half + 1) % 2 * half; x < n; x += step {
				avg := (*at(x-half, y) + *at(x+half, y) + *at(x, y-half) + *at(x, y+half)) / 4
				*at(x, y) = avg + (r.Float64()-0.5)*amp
			}
		}
		amp *= 0.55
	}
	lo, hi := h[0], h[0]
	for _, v := range h {
		lo, hi = math.Min(lo, v), math.Max(hi, v)
	}
	for i := range h {
		v := (h[i] - lo) / (hi - lo)
		h[i] = v * v * 1.1 // flatter lowlands, a few ridges
	}
	return h
}

func writeBytes(b *strings.Builder, name string, v []byte) {
	fmt.Fprintf(b, "const u8 %s[%d] = {", name, len(v))
	for i, x := range v {
		if i%24 == 0 {
			b.WriteString("\n    ")
		}
		fmt.Fprintf(b, "%d,", x)
	}
	b.WriteString("\n};\n\n")
}

func wrap(i int) int { return (i%n + n) % n }

func wrapd(d float64) float64 {
	for d > n/2 {
		d -= n
	}
	for d < -n/2 {
		d += n
	}
	return d
}

func clamp(v, lo, hi float64) float64 { return math.Max(lo, math.Min(hi, v)) }

func must(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
